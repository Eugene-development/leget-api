<?php

declare(strict_types=1);

/**
 * Вывод компонентов и версий из обращения.
 *
 * Ответ на открытый вопрос №3 в docs/architecture/component-lifecycle.md («кто
 * выводит»): решение о выводе — деплой, а не админская операция. Держать его в
 * БД без интерфейса означало бы состояние, которого нет в коде и которое нельзя
 * ни отревьюить, ни откатить вместе с релизом.
 *
 * Отдельный файл, а не колонка в `component_variants.php`: там значение — ЧИСЛО
 * версий, и подмешать в тот же ключ статус нельзя, не сломав `(int)`-приведение
 * в SeedComponentCatalog. Здесь же сведены обе оси жизненного цикла сразу, и это
 * главное, ради чего файл один: их постоянно путают.
 *
 * ─── Две оси, и они независимы ───────────────────────────────────────────────
 *
 * `legacy`   — статус ВЕРСИИ (`component_variants.status`).
 *              «Эта конструкция устарела, есть лучше».
 *              Не предлагается в переключателе · продолжает рендериться.
 *
 * `retired`  — вывод КОМПОНЕНТА со страницы (`components.is_active`).
 *              «Этого блока в новых сборках больше нет».
 *              Не предлагается в списке блоков · продолжает рендериться
 *              и сохраняться у тех, у кого уже стоит.
 *
 * Вывод последней версии НЕ убирает компонент со страницы, и наоборот. Компонент,
 * заменённый другим компонентом (а не другой своей версией), выводится обоими
 * сразу: версии в `legacy`, сам тип в `retired`. Именно этот случай модель версий
 * в одиночку не выражает — переход «компонент → компонент» ею не описан.
 *
 * ⚠️ Тип из `config/templates.php` при этом НЕ удаляется. Удаление оттуда — не
 * вывод, а выключение: блок исчезает со всех сайтов шаблона сразу, а данные
 * тенанта остаются в БД недостижимыми. Здесь ровно наоборот: блок живёт, пока
 * пользователь сам не перейдёт на замену.
 *
 * ─── Инвариант, который проверяет сеятель ────────────────────────────────────
 *
 * Если ВСЕ версии компонента помечены `legacy`, компонент обязан быть в `retired`.
 * Иначе получается блок, который стоит на странице, предлагается новым сайтам —
 * и не имеет ни одной конструкции, которую можно выбрать. `component-catalog:seed`
 * падает на таком сочетании, а не чинит его молча.
 *
 * Зеркало для фронта — `ms/leget-main/src/lib/components/lifecycle.ts`.
 * Дублирование вынужденное и того же рода, что у `design-systems/registry.ts`:
 * переключатель версий живёт в браузере, а конфиг — в PHP. Сверять по паре
 * «шаблон + тип».
 */
return [

    /**
     * Компоненты, выведенные со страницы.
     *
     * Ключи: [templateId][slug] => list<type>. Slug — как в `config/templates.php`.
     */
    'retired' => [
        1 => [
            // 16.08.2026. Блок «Направления» (артикул 1.1.7) заменён компонентом
            // PartnerOffers (1.1.9): у страницы сменился предмет — вместо
            // направлений работы показываются условия партнёров. Это другой
            // компонент, а не новая версия прежнего: другой контракт данных
            // (`offers[]` против `directions[]`) и другой смысл.
            //
            // Данные тенантов остаются под ключом `Direction` и достижимы:
            // тип из templates.php не убран, `getAllowedTypes()` его по-прежнему
            // возвращает, сохранение и порядок блоков работают как раньше.
            '/' => ['Direction'],
        ],
    ],

    /**
     * Версии, выведенные из обращения.
     *
     * Ключи: [templateId][type] => list<version>. Пара «шаблон + тип», как в
     * `config/component_variants.php`: одноимённые блоки разных шаблонов
     * независимы.
     *
     * Статус `draft` этим конфигом не управляется и никогда им не перетирается:
     * здесь выражается только переход active ↔ legacy.
     */
    'legacy' => [
        1 => [
            // Обе версии сразу: выводится не конструкция, а весь блок, поэтому
            // замены внутри компонента нет — заменой служит PartnerOffers.
            'Direction' => [1, 2],
        ],
    ],
];
