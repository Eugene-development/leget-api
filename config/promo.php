<?php

declare(strict_types=1);

/**
 * Настройки системы промокодов.
 *
 * Денежных ставок здесь нет и по умолчанию быть не должно. Формулы
 * вознаграждения куратора платформа не согласовала, и подставить произвольное
 * число значило бы начислить людям деньги по выдуманному правилу. Пока
 * настройка пуста, сделка учитывается, отчёт считает количество и суммы,
 * а колонка вознаграждения честно пуста — см. CuratorCommissionService.
 */
return [
    'code' => [
        /*
         * Алфавит публичного кода. Без 0/O, 1/I/L — код диктуют по телефону
         * и переписывают с бумаги, и пара похожих символов даёт больше
         * ошибок ввода, чем два лишних бита энтропии дают защиты.
         */
        'alphabet' => env('PROMO_CODE_ALPHABET', 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'),

        /*
         * Длина случайной части. 10 символов из 31-буквенного алфавита —
         * около 49 бит: перебором такой код не угадать, а сам он остаётся
         * произносимым. Префикс в длину не входит.
         */
        'length' => (int) env('PROMO_CODE_LENGTH', 10),

        'prefix' => env('PROMO_CODE_PREFIX', 'LG'),
    ],

    'defaults' => [
        /** Срок действия по умолчанию, если куратор не задал свой. */
        'valid_days' => (int) env('PROMO_DEFAULT_VALID_DAYS', 30),

        'currency' => env('PROMO_DEFAULT_CURRENCY', 'RUB'),
    ],

    /*
     * Вознаграждение куратора.
     *
     * `fixed_per_closed_deal` — фиксированная сумма за закрытую сделку.
     * `percent_of_platform_commission` — процент от комиссии платформы,
     * которая приходит вместе со сведениями о сделке.
     *
     * Обе настройки по умолчанию NULL. Заполнена может быть только одна:
     * два правила одновременно означали бы два ответа на вопрос «сколько».
     */
    'commission' => [
        'fixed_per_closed_deal' => env('PROMO_COMMISSION_FIXED', null),
        'percent_of_platform_commission' => env('PROMO_COMMISSION_PERCENT', null),
        'currency' => env('PROMO_COMMISSION_CURRENCY', 'RUB'),
    ],

    /*
     * Передача офлайн-конверсий в Яндекс.
     *
     * Закрытая сделка всегда попадает в реестр `conversions` (это outbox).
     * Реальная отправка не выполняется: у платформы нет ни credentials,
     * ни согласованного API. Флаг существует, чтобы точку подключения было
     * видно из конфига, а не только из кода слушателя.
     */
    'offline_conversions' => [
        'enabled' => (bool) env('PROMO_OFFLINE_CONVERSIONS', true),
    ],
];
